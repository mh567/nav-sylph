'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const bcrypt = require('bcrypt');
const { installation } = require('./helpers/installation');

test('HTTP: independent administrator devices version modules and navigation, replay after restart and log out independently', async t => {
    const app = await installation(t);
    fs.writeFileSync(path.join(app.dir, '.admin-password.json'), JSON.stringify({ passwordHash: await bcrypt.hash('StrongPass123!', 4) }));
    await app.start();
    const login = async () => (await app.request('/api/verify-password', { password: 'StrongPass123!', body: {} })).headers.get('set-cookie').split(';')[0];
    const a = await login(), b = await login();
    const get = async (route, cookie = a) => (await app.request(route, { cookie })).json();
    const initial = await get('/api/config');
    const base = await get('/api/modules/config');
    assert.ok(Number.isSafeInteger(base.revision));
    const body = { revision: base.revision, operationId: 'modules-one', enabledModules: ['memo'], pollInterval: 30 };
    const results = await Promise.all([body, { ...body, operationId: 'competing', pollInterval: 60 }].map(body => app.request('/api/modules/config', { cookie: a, body })));
    assert.deepEqual(results.map(r => r.status).sort(), [200, 409]);
    const winner = results[0].status === 200 ? body : { ...body, operationId: 'competing', pollInterval: 60 };
    const saved = await results.find(r => r.status === 200).json();
    assert.equal((await get('/api/modules/config', b)).pollInterval, winner.pollInterval);
    const nav = await get('/api/admin/navigation', b);
    nav.config.searchEngines = [{ id: 'custom', name: 'Custom', url: 'https://example.com/?q=' }]; nav.config.searchEngine = 'custom';
    assert.equal((await app.request('/api/admin/navigation', { cookie: b, body: { ...nav, operationId: 'nav-one' } })).status, 200);
    assert.deepEqual(await get('/api/config'), initial);
    assert.equal((await get('/api/admin/navigation')).config.searchEngine, 'custom');
    await app.stop(); await app.start();
    assert.deepEqual(await (await app.request('/api/modules/config', { cookie: a, body: winner })).json(), saved);
    assert.equal((await app.request('/api/modules/config', { cookie: a, body: { ...winner, pollInterval: 10 } })).status, 409);
    assert.equal((await app.request('/api/modules/config', { cookie: a, body: { pollInterval: 10 } })).status, 409);
    assert.equal((await app.request('/api/logout', { cookie: a, body: {} })).status, 200);
    assert.equal((await app.request('/api/admin/navigation', { cookie: a })).status, 401);
    assert.equal((await app.request('/api/admin/navigation', { cookie: b })).status, 200);
    assert.equal((await get('/api/modules/config', b)).revision, saved.revision);
    assert.equal((await get('/api/modules/config', b))._sync, undefined);
});

test('HTTP: module server changes invalidate stale layouts and expired receipts reconcile by revision', async t => {
    const app = await installation(t);
    fs.writeFileSync(path.join(app.dir, '.admin-password.json'), JSON.stringify({ passwordHash: await bcrypt.hash('StrongPass123!', 4) }));
    await app.start();
    const cookie = (await app.request('/api/verify-password', { password: 'StrongPass123!', body: {} })).headers.get('set-cookie').split(';')[0];
    const get = async () => (await app.request('/api/modules/config', { cookie })).json();
    const base = await get();
    const result = await app.request('/api/modules/servers', { cookie, body: { id: 'machine', name: 'Machine', url: 'https://127.0.0.1:4195', revision: base.revision, operationId: 'server-one' } });
    assert.equal(result.status, 200);
    assert.equal((await app.request('/api/modules/config', { cookie, body: { revision: base.revision, operationId: 'stale-layout', widgets: [] } })).status, 409);
    const current = await get();
    assert.ok(current.revision > base.revision);
    assert.equal(current.servers[0].name, 'Machine');
    const body = { revision: current.revision, operationId: '__proto__', pollInterval: 60 };
    const saved = await (await app.request('/api/modules/config', { cookie, body })).json();
    assert.equal(saved.success, true);
    assert.deepEqual(await (await app.request('/api/modules/config', { cookie, body })).json(), saved);
    await app.stop();
    const file = path.join(app.dir, '.modules.json');
    const data = JSON.parse(fs.readFileSync(file));
    data._sync.receipts.__proto__.at = Date.now() - 86400001;
    fs.writeFileSync(file, JSON.stringify(data));
    await app.start();
    assert.equal((await app.request('/api/modules/config', { cookie, body })).status, 409);
    const latest = await get();
    assert.equal(latest.pollInterval, 60);
    assert.equal(latest.revision, saved.revision);
    assert.equal((await app.request('/api/modules/config', { cookie, body: { revision: latest.revision, operationId: 'coordinated', widgets: [{ id: 'memo', side: 'right', order: 0 }] } })).status, 200);
    assert.equal((await get()).servers[0].name, 'Machine');
    const beforeDelete = await get();
    const deletion = { revision: beforeDelete.revision, operationId: 'delete-server' };
    const deleted = await (await app.request('/api/modules/servers/machine', { cookie, method: 'DELETE', body: deletion })).json();
    assert.equal(deleted.success, true);
    assert.deepEqual(await (await app.request('/api/modules/servers/machine', { cookie, method: 'DELETE', body: deletion })).json(), deleted);
    assert.equal((await app.request('/api/modules/servers', { cookie, body: { id: 'machine', name: 'Stale', url: 'https://127.0.0.1:4195', revision: beforeDelete.revision, operationId: 'stale-target' } })).status, 409);
    assert.equal((await get()).servers.length, 0);
    assert.equal(fs.statSync(file).mode & 0o777, 0o600);
    fs.writeFileSync(file, '{broken configuration');
    assert.equal((await app.request('/api/modules/config', { cookie })).status, 500);
    assert.equal((await app.request('/api/modules/config', { cookie, body: { revision: deleted.revision, operationId: 'corrupt-save', pollInterval: 15 } })).status, 500);
    assert.equal(fs.readFileSync(file, 'utf8'), '{broken configuration');
});
